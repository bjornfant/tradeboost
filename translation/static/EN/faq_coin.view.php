<h2>What does proof or frosted mean for coins?</h2>
<p>
Proof coins are specially struck coins that are made using polished dies and planchets, resulting in a highly reflective, mirror-like surface on the coin's fields and a frosted appearance on the raised design elements. The frosted areas contrast sharply with the mirrored fields, resulting in a very sharp and clear design. 
<br><br>
Frosted proof gold coins are made using a specialized minting process that involves multiple strikes with specially polished dies. The result is a coin with a frosted, or matte, finish on the raised design elements and a mirrored surface on the fields. This contrast between the frosted and mirrored surfaces creates a sharp and clear design, making the details of the coin's design stand out.They are typically sold in special presentation cases and are considered to be among the most desirable and valuable coins in the numismatic world.
</p>

