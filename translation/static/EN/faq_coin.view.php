<h2>What is "margin scheme" I see on some coins?</h2>
<p>
The margin scheme is a tax regulation that applies to the sale of second-hand goods, including coins, in some countries.
<br><br>
Under the margin scheme, the VAT (value-added tax) is only payable on the profit margin made by the seller on the sale of a second-hand good, rather than on the full sale price. This means that if the seller bought the item for a certain price and then sells it for a higher price, they only pay VAT on the difference between the purchase price and the selling price.
<br><br>
The margin scheme is designed to prevent double taxation on second-hand goods, as the seller has already paid VAT on the purchase of the item. It also helps to make second-hand goods more affordable by reducing the overall cost to the buyer.
<br><br>
In the context of coins, the margin scheme can be particularly relevant for coin dealers who deal in second-hand or collector coins. By using the margin scheme, they are able to reduce their VAT liability and offer their customers a more competitive price for the coins they sell.
<br><br>
It is worth noting that the margin scheme is not available in all countries, and the specific rules and regulations surrounding it can vary depending on the jurisdiction. Coin dealers and collectors should consult with their local tax authority or a tax professional to determine if the margin scheme applies to their business and how to properly implement it.</p>

