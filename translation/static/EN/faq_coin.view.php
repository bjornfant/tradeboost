<h2>What is the difference between proof and reverse proof?</h2>
<p>
The main difference between proof and reverse proof coins is the way that the design elements on the coin's surface are treated during the minting process.
<br><br>
Reverse proof coins are struck in the same way as proof coins, but the treatment of the design elements is reversed. In the case of reverse proof coins, the design elements on the coin's surface are polished to a mirror-like finish, while the fields are treated with a matte, or frosted finish. This creates the opposite effect of proof coins, with the design elements appearing shiny while the background is dull. Reverse proof coins are also typically produced in limited quantities and are highly sought after by collectors.
<br><br>
Overall, while both proof and reverse proof coins have a similar level of detail and quality in their designs, the different finishes create a unique visual effect that can make them stand out in a collection.					</p>

