					<h2>Die Geschichte der Münzen in Europa</h2>
					<p>
					<small>Text von <a href="https://www.rarecoin.de/">Rarecoin.de</a></small>
					</p>
					<p>
					Die numismatische Moderne begann in Europa um 1500 in den habsburgischen Ländern. Mit der Prägung des Tiroler Guldengroschens als erste große <a href="https://www.rarecoin.de/">Silbermünze</a> im Wert eines rheinischen Goldguldens im Jahr 1486 legte Erzherzog Sigismund "Reich an Münzen" das Modell für den erfolgreichsten Münztyp der nächsten 400 Jahre.
 					</p>
					<p>
					Den Namen für dieses Erfolgsmodell gaben die Grafen von Schlick mit ihrem Silberbergwerk Joachimstal, woher auch der Begriff "Taler" stammt. Die Silbermünze wurde in ganz Europa und darüber hinaus unter verschiedenen Namen geprägt - in Skandinavien als Rigsdaler, in Italien als De Larger, in Spanien als Peso, in Frankreich als Ecu, in England als Crown und in den USA als Dollar. Trotz der großen Beliebtheit dieser wichtigsten europäischen Handelswährung vom 16. bis zum 19. Jahrhundert ist die moderne Münzprägung in der ganzen Bandbreite ihrer Typen und Darstellungen so umfangreich und kaum quantifizierbar, dass wir an dieser Stelle nur einige besondere Elemente und Aspekte erwähnen können.
					</p>
					<p>					 
					Sogar in der Schweiz waren um 1900 über 800 verschiedene Münzsorten vorhanden, da viele verschiedene Herrscher ihre eigenen Münzen prägten. Unter den Münzbildern befinden sich Porträts von fast allen berühmten europäischen Persönlichkeiten: sei es die "Virgin Queen" Elisabeth I. oder der "Lord Protector" Oliver Cromwell , der "Sun King" Ludwig XIV. oder der "Emperor of the French" Napoléon Bonaparte), oder der "Lion of the North" Gustav II. Adolf oder der "Savior of Vienna" Johann III. Sobieski - sie alle haben ihre Spuren in der Welt der Münzen und Medaillen hinterlassen und sind somit Teil der europäischen Geschichte. 
					</p>
					<p>					 
					Und die Bilder der Münzen können uns helfen, noch mehr zu verstehen als die sich ständig verändernde Münzgeschichte Europas. Vom 16. bis zum Beginn des 19. Jahrhunderts prägte Spanien Münzen aus groben, manchmal kantigen Abgüssen von grobem Silber aus den Minen von Mexiko und Peru. Im Volksmund wurden diese Münzen "Schiffsgeld" genannt, weil man annahm, dass sie während der Überfahrt aus den Kolonien entstanden waren. Im Jahr 1795, während der Französischen Revolution, wurde zum ersten Mal in einem europäischen Staat eine auf dem Dezimalsystem basierende Währung eingeführt, mit dem Franc als Standard-Silbermünze.
					</p>
					<p>					 
					Neben den etablierten Münzformen gab es in Europa auch zahlreiche Sondermünzen. Im 17./18. Jahrhundert zum Beispiel wurden in Schweden aufgrund von Silbermangel mehrere Kilogramm schwere Kupferplatten als Zahlungsmittel ausgegeben. Zur gleichen Zeit führte ein Mangel an Kleingeld in England zu zahlreichen privaten Münzen (Token) mit allen möglichen attraktiven Designs. Eine interessante Mischung aus Münze und Jeton sind die Schraubmünzen - hohle, bedruckte Medaillenschachteln mit Einsätzen aus farbigem Papier, die Serienbilder enthalten. Die zahlreichen Neuausgaben gängiger Münzsorten sind ebenfalls ein beliebtes Sammelgebiet für europäische Münzen: Der holländische Löwentaler (oder leeuwendaaler, "Löwentaler") zum Beispiel wurde im 17. Jahrhundert von vielen Münzstätten in Deutschland, Dänemark und Italien nachgeahmt. Die umfangreichen militärischen Aktivitäten der Neuzeit führten auch zu zahlreichen Ausgaben von Not- und Belagerungsgeld, z.B. in Form der quadratischen Klippe (von schwedisch "klippe", "mit der Schere schneiden").

